// Производственный календарь 2027: праздники, переносы, рабочие дни по месяцам.
'use strict';

// ---------- Календарь 2027 ----------
const YEAR = 2027;
const DAY_MS = 864e5;
const T0 = Date.UTC(YEAR, 0, 1);
const N = Math.round((Date.UTC(YEAR + 1, 0, 1) - T0) / DAY_MS);

const MONTHS = ['Январь','Февраль','Март','Апрель','Май','Июнь','Июль','Август','Сентябрь','Октябрь','Ноябрь','Декабрь'];
const MON_GEN = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];
const MON_SH = ['янв','фев','мар','апр','май','июн','июл','авг','сен','окт','ноя','дек'];
const MON_LETTER = ['Я','Ф','М','А','М','И','И','А','С','О','Н','Д'];
const DOW = ['пн','вт','ср','чт','пт','сб','вс'];
const DOW_FULL = ['понедельник','вторник','среда','четверг','пятница','суббота','воскресенье'];

// Нерабочие праздничные дни — ст. 112 ТК
const HOLIDAYS = {
  '01-01':'Новогодние каникулы','01-02':'Новогодние каникулы','01-03':'Новогодние каникулы',
  '01-04':'Новогодние каникулы','01-05':'Новогодние каникулы','01-06':'Новогодние каникулы',
  '01-07':'Рождество Христово','01-08':'Новогодние каникулы',
  '02-23':'День защитника Отечества','03-08':'Международный женский день',
  '05-01':'Праздник Весны и Труда','05-09':'День Победы',
  '06-12':'День России','11-04':'День народного единства'
};
// Перенесённые выходные — постановление № 1187 и ч. 2 ст. 112 ТК
const TRANSFERS = {
  '02-22':'Выходной, перенесённый с субботы 20 февраля',
  '05-03':'Выходной: 1 мая выпало на субботу',
  '05-10':'Выходной: 9 мая выпало на воскресенье',
  '06-14':'Выходной: 12 июня выпало на субботу',
  '11-05':'Выходной, перенесённый с субботы 2 января',
  '12-31':'Выходной, перенесённый с воскресенья 3 января'
};
const WORKING_WEEKEND = { '02-20':'Рабочая суббота: выходной перенесён на 22 февраля' };
const SHORT_DAYS = { '02-20':1, '04-30':1, '06-11':1, '11-03':1 };
const EXPECTED_WORKDAYS = [15,19,22,22,19,21,22,22,22,21,20,22];

const pad = n => String(n).padStart(2,'0');
const DAYS = [];
for (let i = 0; i < N; i++) {
  const dt = new Date(T0 + i * DAY_MS);
  const m = dt.getUTCMonth(), d = dt.getUTCDate(), dow = (dt.getUTCDay() + 6) % 7;
  const key = pad(m + 1) + '-' + pad(d);
  const hol = HOLIDAYS[key] || null, tr = TRANSFERS[key] || null, ws = WORKING_WEEKEND[key] || null;
  const off = !!hol || !!tr || (dow >= 5 && !ws);
  DAYS.push({ i, m, d, dow, key, hol, tr, ws, short: !!SHORT_DAYS[key], off, work: !off });
}
const MONTH_INFO = [];
for (let m = 0; m < 12; m++) {
  const start = DAYS.findIndex(D => D.m === m);
  let len = 0, work = 0, shorts = 0;
  for (let i = start; i < N && DAYS[i].m === m; i++) { len++; if (DAYS[i].work) { work++; if (DAYS[i].short) shorts++; } }
  MONTH_INFO.push({ start, len, work, hours: work * 8 - shorts });
}
MONTH_INFO.forEach((M, m) => { if (M.work !== EXPECTED_WORKDAYS[m]) console.warn('Рабочие дни не совпали', m + 1, M.work); });

// Последовательности нерабочих дней (выходные + праздники)
const OFF_RUNS = [];
for (let i = 0; i < N; i++) { if (!DAYS[i].off) continue; let j = i; while (j + 1 < N && DAYS[j + 1].off) j++; OFF_RUNS.push({ a: i, b: j, len: j - i + 1 }); i = j; }
// Первый рабочий день после январских каникул (11 января)
const JAN_START = OFF_RUNS[0].b + 1;
